"""Regenerate the CLI --help block in README.md from the live CLI.

Run automatically by pre-commit; can also be run manually:
    uv run python scripts/update_cli_docs.py
"""

import re
import sys
from pathlib import Path

from click.testing import CliRunner

from fit_changedetector.cli import cli

README = Path(__file__).resolve().parent.parent / "README.md"
START = "<!-- BEGIN CLI HELP (auto-generated by scripts/update_cli_docs.py - do not edit by hand) -->"
END = "<!-- END CLI HELP -->"

COMMANDS = [
    ([], "changedetector --help"),
    (["add-hash-key"], "changedetector add-hash-key --help"),
    (["compare"], "changedetector compare --help"),
]


def _help_block(args, prompt):
    result = CliRunner().invoke(cli, [*args, "--help"], prog_name="changedetector")
    lines = [f"    $ {prompt}"]
    lines += [f"    {line}" if line else "" for line in result.output.splitlines()]
    return "\n".join(lines)


def generate():
    return "\n\n".join(_help_block(args, prompt) for args, prompt in COMMANDS)


def main():
    content = README.read_text()
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(content):
        raise SystemExit(f"README.md is missing the {START} / {END} markers")
    new_content = pattern.sub(f"{START}\n{generate()}\n{END}", content)
    if new_content == content:
        return 0
    README.write_text(new_content)
    print("README.md CLI help block was out of date and has been regenerated.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
